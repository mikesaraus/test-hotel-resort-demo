      lines, heads, gross: r2(gross), total, discount: r2(gross - total),
      vatRemoved: r2(elig - exemptBase), scDisc: r2(scDisc),
      vatable: r2(nonElig / 1.12), vat: r2(nonElig - nonElig / 1.12), vatExempt: r2(exemptBase)
